Event _buildSeedEvent({
  required int index,
  required _SeedSpec spec,
  required dynamic club,
  required dynamic organizer,
  required List<dynamic> participants,
  required DateTime createdAt,
}) {
  final ids = [for (final p in participants) p.id as String];
  return Event(
    id: 'seed_event_${spec.sportId}',
    clubId: club.id as String,
    clubName: club.name as String,
    clubMemberCount: club.memberCount as int,
    clubDescription:
        'Official community sessions by ${club.name} in ${club.city}. Open for athletes looking to train and connect together.',
    organizerName: organizer.name as String,
    participantIds: ids,
    name: spec.name,
    sport: ClubSport.byId(spec.sportId),
    startsAt: spec.startsAt,
    recurrence: spec.recurrence,
    isVirtual: spec.isVirtual,
    location: spec.location,
    description: spec.description,
    isDiscoverable: true,
    kind: spec.kind,
    paceUnit: null,
    paceRanges: const [],
    distance: spec.distanceKm,
    distanceUnit: DistanceUnit.km,
    surface: spec.surface,
    womenOnly: false,
    clubMembersOnly: false,
    capacity: null,
    attendeeCount: ids.length,
    isAttending: false,
    createdAt: createdAt,
  );
}